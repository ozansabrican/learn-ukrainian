/**
 * Build step (runs before dev, test and on Vercel):
 *  - src/generated/decks.ts  ← word lists extracted from ../index.html
 *  - src/generated/page.ts   ← the app's HTML and admin/admin.html, bundled into the function
 *    (Vercel's Fastify builder doesn't serve a public/ folder)
 * Both outputs are git-ignored; index.html stays the source of truth.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { withKeys } from '../src/keyed.js';
import { readDecksFromHtml } from '../src/source.js';

const root = resolve(import.meta.dirname, '..');
const htmlPath = resolve(root, process.env.WEB_ROOT ?? '..', 'index.html');

const decks = withKeys(readDecksFromHtml(htmlPath));

mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(
  join(root, 'src/generated/decks.ts'),
  `// Generated by scripts/gen.ts from index.html — do not edit.\n` +
    `import type { DeckName } from '../decks.js';\n` +
    `import type { KeyedItem } from '../routes/decks.js';\n\n` +
    `export const decks: Record<DeckName, KeyedItem[]> = ${JSON.stringify(decks, null, 1)};\n`,
);

writeFileSync(
  join(root, 'src/generated/page.ts'),
  `// Generated by scripts/gen.ts from index.html — do not edit.\n` +
    `export const indexHtml = ${JSON.stringify(readFileSync(htmlPath, 'utf8'))};\n` +
    `export const adminHtml = ${JSON.stringify(readFileSync(join(root, 'admin/admin.html'), 'utf8'))};\n`,
);

const counts = Object.entries(decks).map(([d, items]) => `${d} ${items.length}`).join(', ');
console.log(`gen: ${counts}`);
